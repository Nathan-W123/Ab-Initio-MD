# 6-31G*: one Cartesian d shell (single primitive) on Li-Ar.
_6_31G_STAR_D = {
    "Li": 0.2, "Be": 0.4, "B": 0.6, "C": 0.8, "N": 0.8, "O": 0.8, "F": 0.8,
    "Ne": 0.8, "Na": 0.175, "Mg": 0.175, "Al": 0.325, "Si": 0.45, "P": 0.55,
    "S": 0.65, "Cl": 0.75, "Ar": 0.85,
}
# 6-31G**: additionally one p shell on H and He.
_6_31G_STARSTAR_P = {"H": 1.1, "He": 1.1}


def _add_shell(base: _BasisDict, l: int, exponents: dict[str, float]) -> _BasisDict:
    out = {el: list(shells) for el, shells in base.items()}
    for el, a in exponents.items():
        out[el].append([l, [a, 1.0]])
    return out


_6_31G_STAR = _add_shell(_6_31G, 2, _6_31G_STAR_D)
_6_31G_STARSTAR = _add_shell(_6_31G_STAR, 1, _6_31G_STARSTAR_P)

BASIS_SETS: dict[str, _BasisDict] = {
    "sto-3g": _STO_3G,
    "6-31g": _6_31G,
    "6-31g*": _6_31G_STAR,
    "6-31g**": _6_31G_STARSTAR,
    "cc-pvdz": _CC_PVDZ,
}

_ALIASES = {
    "sto3g": "sto-3g",
    "631g": "6-31g",
    "6-31g(d)": "6-31g*",
    "631g*": "6-31g*",
    "6-31g(d,p)": "6-31g**",
    "631g**": "6-31g**",
    "ccpvdz": "cc-pvdz",
}


def normalize_basis_name(name: str) -> str:
    """Canonical (lower-case) basis name: '6-31G*' -> '6-31g*', '6-31G(d)' -> '6-31g*'."""
    key = "".join(str(name).split()).lower()
    key = _ALIASES.get(key, key)
    if key not in BASIS_SETS:
        raise ValueError(
            f"Unknown basis set {name!r}. Available: {', '.join(available_basis_sets())}"
        )
    return key


def available_basis_sets() -> list[str]:
    return list(BASIS_SETS)


def get_basis_shells(name: str, symbol: str) -> list[tuple[int, np.ndarray, np.ndarray]]:
    """
    Shells of ``symbol`` in basis ``name`` as (l, exponents (nprim,),
    coefficients (nprim, nctr)) in file order. Raises ValueError for an
    unknown basis or an element the basis does not cover.
    """
    key = normalize_basis_name(name)
    sym = normalize_symbol(symbol)
    data = BASIS_SETS[key]
    if sym not in data:
        raise ValueError(
            f"Basis set {key!r} has no data for element {sym!r} "
            f"(available: {', '.join(data)})"
        )
    shells = []
    for entry in data[sym]:
        l = int(entry[0])
        rows = np.array(entry[1:], dtype=float)
        shells.append((l, rows[:, 0].copy(), rows[:, 1:].copy()))
    return shells
