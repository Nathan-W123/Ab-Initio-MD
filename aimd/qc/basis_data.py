"""
Gaussian basis-set data for H-Ar: STO-3G, 6-31G, 6-31G*, 6-31G**, cc-pVDZ.

Format (the PySCF / NWChem row layout, so general contractions are explicit):

    {element: [[l, [exp_1, c_11, c_12, ...], [exp_2, c_21, c_22, ...], ...], ...]}

``l`` is the angular momentum, each row is one primitive (exponent in bohr^-2)
followed by its coefficient in each contracted function of the shell. The
coefficients refer to *normalized* primitives, as in every basis library;
:mod:`aimd.qc.basis` renormalizes the contracted functions, so the overall
scale of a column is irrelevant. Pople "SP" shells are stored as separate s
and p shells with shared exponents.

Sources
-------
STO-3G   Hehre, Stewart & Pople, J. Chem. Phys. 51, 2657 (1969);
         Hehre, Ditchfield, Stewart & Pople, J. Chem. Phys. 52, 2769 (1970).
6-31G    Ditchfield, Hehre & Pople, J. Chem. Phys. 54, 724 (1971);
         Hehre, Ditchfield & Pople, J. Chem. Phys. 56, 2257 (1972);
         Dill & Pople, J. Chem. Phys. 62, 2921 (1975) (Li, Be);
         Francl et al., J. Chem. Phys. 77, 3654 (1982) (Na-Ar).
6-31G*   6-31G + one Cartesian d shell on Li-Ar
         (Hariharan & Pople, Theor. Chim. Acta 28, 213 (1973); Francl et al.).
6-31G**  6-31G* + one p shell (exponent 1.1) on H and He.
cc-pVDZ  Dunning, J. Chem. Phys. 90, 1007 (1989) (H, Li-Ne);
         Woon & Dunning, J. Chem. Phys. 98, 1358 (1993) (Al-Ar);
         Woon & Dunning, J. Chem. Phys. 100, 2975 (1994) (He); Na, Mg as
         distributed by the EMSL library (2014).

Provenance and cross-check
--------------------------
The numbers were taken from HF-SCF-Engine (backend/basis_data.py and
basis_cache.json) and then cross-checked, exponent by exponent and
coefficient by coefficient, against PySCF 2.14's own copies
(``pyscf.gto.basis.load(name, symbol)``, i.e. the EMSL/BSE files). Every
discrepancy was resolved in favour of PySCF, so the data below are identical
to PySCF's (shortest round-trip float repr) and the 6-31G* / 6-31G** shells
equal PySCF's "6-31g*" / "6-31g**" entries exactly. Problems found in the
HF-SCF-Engine sources:

  - STO-3G Na-Ar: wrong exponents and 2s/2p contraction coefficients reused
    for the n = 3 shells (the 3sp contraction differs).
  - 6-31G Li-Ne (except C): the C core/valence contraction coefficients had
    been reused; N, F, Ne exponents were also off by up to 9 %.
  - 6-31G Na-Ar: wrong shell structure (the 6-primitive 2sp shell was
    missing; the 3sp shell had 2-3 primitives instead of 3).
  - cc-pVDZ (basis_cache.json): only the first column of each general
    contraction was kept, so e.g. O had [2s1p1d] instead of [3s2p1d]; the Ar
    d shell was corrupt (677 primitives). The first cache column of every s
    and p shell lies in the span of the shells below to 1e-15 (relative
    least-squares residual), i.e. both sources describe the same basis.
    PySCF stores the "optimized" general contraction (the most diffuse
    s/p primitive is dropped from the contracted columns because it is also
    a separate shell); this spans exactly the same space as the original
    Dunning contraction, so SCF energies are unaffected.
  - cc-pVDZ Li, Be, Na, Mg: PySCF's (EMSL 2014) d exponents 0.1239, 0.238,
    0.0973, 0.187 differ from the current BSE revision (Prascher et al.,
    Theor. Chem. Acc. 128, 69 (2011): 0.1144, 0.2354, 0.0928, 0.1932). We
    follow PySCF so that energies can be compared with it directly; codes
    using the newer revision (e.g. recent Psi4) differ for these elements.
"""

